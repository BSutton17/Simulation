import { KINGDOM_IDS, type KingdomId } from "../../../src/data/kingdoms.js";
import { runHeadlessMatch } from "../headless.js";
import {
  ACTIVE_POPULATION,
  factoryFor,
  orderedPairings,
  seatProfiles,
  type StrategyPopulation,
} from "./population.js";
import { seedsFor, type SeedPoolName } from "./seeds.js";
import {
  SAMPLERS,
  samplerSeed,
  type CompositionSampler,
  type SamplerContext,
} from "./samplers.js";

/**
 * Job planning and execution — the atomic unit of evaluation work.
 *
 * Splitting "decide what to run" from "run it" is what makes parallel
 * evaluation safe: the plan is a pure function of the configuration, so worker
 * count and completion order cannot influence which matches happen, what seeds
 * they use, or how their results are combined. Aggregation later walks the plan
 * in order and looks each outcome up by id, so a worker finishing early changes
 * nothing.
 */

export type MatchFormat = "duel" | "ffa4" | "ffa7";

/** Everything needed to reproduce exactly one match. */
export interface MatchJob {
  /** Deterministic identifier — also the aggregation key. */
  id: string;
  format: MatchFormat;
  seats: number;
  /** Kingdoms in SEAT order (rotation already applied). */
  kingdoms: KingdomId[];
  /** Strategy profile id per seat. */
  profiles: string[];
  seed: number;
  maxTicks: number;
  /** Ordered strategy pairing this match belongs to, e.g. "economic/random". */
  pairingKey: string;
  pairingA: string;
  pairingB: string;
  mirror: boolean;
  /** Duels only: the matchup, in canonical (a, b) order. */
  duelA?: KingdomId;
  duelB?: KingdomId;
  /** FFA only: the sampled composition, in canonical order. */
  compositionKey?: string;
}

/** The compact result a worker returns. Deliberately small — full telemetry
 *  would dominate the cost of moving results between threads. */
export interface MatchOutcome {
  id: string;
  /** Kingdom that won, or null on a timeout with no winner. */
  winnerKingdom: string | null;
  /** Seat index of the winner, or null. */
  winnerSeat: number | null;
  endedAtTick: number;
  /** True when the tick cap was reached — a GAME outcome, not a failure. */
  timedOut: boolean;
  /** Finishing position per seat index (1 = winner). */
  placements: number[];
}

export interface PlanOptions {
  pool: SeedPoolName;
  population: StrategyPopulation;
  maxTicks: number;
  duel: { enabled: boolean; seedsPerPairing: number; pairings?: [KingdomId, KingdomId][] };
  ffa4: { enabled: boolean; seedsPerPairing: number; compositions: number; sampler: string };
  ffa7: { enabled: boolean; seedsPerPairing: number; compositions: number; sampler: string };
  /** Optional bias for context-aware samplers. */
  samplerContext?: SamplerContext;
}

/** All C(16,2) = 120 unordered kingdom pairings, in canonical order. */
export function allDuelPairings(): [KingdomId, KingdomId][] {
  const out: [KingdomId, KingdomId][] = [];
  for (let i = 0; i < KINGDOM_IDS.length; i++) {
    for (let j = i + 1; j < KINGDOM_IDS.length; j++) {
      out.push([KINGDOM_IDS[i]!, KINGDOM_IDS[j]!]);
    }
  }
  return out;
}

/**
 * A SUBSET of duel pairings with even kingdom representation.
 *
 * Never take a prefix of `allDuelPairings()`. That list is generated by nested
 * `i < j` loops, so an early kingdom appears in far more of the first N
 * pairings than a late one: `slice(0, 24)` gives Water fifteen matchups and
 * Dark exactly one, and `slice(0, 60)` still gives Water fifteen against Dark's
 * four. A cheap tier built that way does not measure a weak, late-roster
 * kingdom at all — it measures one arbitrary matchup and reports it as a win
 * rate, which is how the Step 9 screening tier came to disagree with reference
 * depth about whether Dark was violating its bound.
 *
 * This greedily takes the pairing whose two kingdoms have been seen least so
 * far, so appearances stay within one of each other at any budget. Fully
 * deterministic: no seed, same subset every time.
 */
export function balancedDuelPairings(count: number): [KingdomId, KingdomId][] {
  const all = allDuelPairings();
  if (count >= all.length) return all;

  const seen = new Map<KingdomId, number>(KINGDOM_IDS.map((k) => [k, 0]));
  const remaining = new Set(all.map((_, i) => i));
  const chosen: [KingdomId, KingdomId][] = [];

  while (chosen.length < count && remaining.size > 0) {
    let bestIndex = -1;
    let bestCost = Infinity;
    for (const index of remaining) {
      const [a, b] = all[index]!;
      // Cost is dominated by the more-seen of the two, so a pairing cannot be
      // chosen just because one of its kingdoms is starved.
      const cost = Math.max(seen.get(a)!, seen.get(b)!) * 100 + seen.get(a)! + seen.get(b)!;
      if (cost < bestCost) {
        bestCost = cost;
        bestIndex = index;
      }
    }
    const [a, b] = all[bestIndex]!;
    seen.set(a, seen.get(a)! + 1);
    seen.set(b, seen.get(b)! + 1);
    remaining.delete(bestIndex);
    chosen.push([a, b]);
  }
  // Canonical order so the plan is stable regardless of selection order.
  return chosen.sort((x, y) => x[0].localeCompare(y[0]) || x[1].localeCompare(y[1]));
}

function pickSampler(name: string): CompositionSampler {
  const sampler = SAMPLERS[name];
  if (!sampler) throw new Error(`unknown sampler "${name}"`);
  return sampler;
}

/** The compositions an FFA format will be evaluated over. */
export function planCompositions(
  seats: number,
  cfg: { enabled: boolean; compositions: number; sampler: string },
  pool: SeedPoolName,
  context?: SamplerContext,
): KingdomId[][] {
  if (!cfg.enabled) return [];
  return pickSampler(cfg.sampler).sample(
    seats,
    cfg.compositions,
    samplerSeed(pool, seats),
    context,
  );
}

/** The sampler an FFA format will use, for provenance. */
export function samplerFor(name: string): CompositionSampler {
  return pickSampler(name);
}

/**
 * The complete, ordered list of matches an evaluation will run.
 *
 * Pure: same options in, same jobs out, every time.
 */
export function planJobs(options: PlanOptions): MatchJob[] {
  const jobs: MatchJob[] = [];
  const pairings = orderedPairings(options.population);

  if (options.duel.enabled) {
    const duels = options.duel.pairings ?? allDuelPairings();
    for (const [a, b] of duels) {
      const label = `${a}-vs-${b}`;
      for (const pairing of pairings) {
        const seeds = seedsFor(options.pool, label, pairing.key, options.duel.seedsPerPairing);
        seeds.forEach((seed, index) => {
          jobs.push({
            id: `duel|${label}|${pairing.key}|${index}`,
            format: "duel",
            seats: 2,
            kingdoms: [a, b],
            profiles: seatProfiles(pairing, 2),
            seed,
            maxTicks: options.maxTicks,
            pairingKey: pairing.key,
            pairingA: pairing.a,
            pairingB: pairing.b,
            mirror: pairing.mirror,
            duelA: a,
            duelB: b,
          });
        });
      }
    }
  }

  for (const [format, seats, cfg] of [
    ["ffa4", 4, options.ffa4],
    ["ffa7", 7, options.ffa7],
  ] as const) {
    if (!cfg.enabled) continue;
    const compositions = planCompositions(seats, cfg, options.pool, options.samplerContext);
    compositions.forEach((composition, compositionIndex) => {
      const label = composition.join("+");
      pairings.forEach((pairing, pairingIndex) => {
        const seeds = seedsFor(options.pool, label, pairing.key, cfg.seedsPerPairing);
        seeds.forEach((seed, index) => {
          // Seat rotation must be a function of the PLAN, never of how many
          // matches have completed: a running counter would make the roster
          // depend on execution order, which parallelism does not preserve.
          const rotation =
            (compositionIndex * pairings.length * cfg.seedsPerPairing +
              pairingIndex * cfg.seedsPerPairing +
              index) %
            seats;
          const rotated = composition.map((_, i) => composition[(i + rotation) % seats]!);
          jobs.push({
            id: `${format}|${label}|${pairing.key}|${index}`,
            format,
            seats,
            kingdoms: rotated,
            profiles: seatProfiles(pairing, seats),
            seed,
            maxTicks: options.maxTicks,
            pairingKey: pairing.key,
            pairingA: pairing.a,
            pairingB: pairing.b,
            mirror: pairing.mirror,
            compositionKey: label,
          });
        });
      });
    });
  }

  return jobs;
}

/**
 * Runs one job through the production engine.
 *
 * Shared verbatim by the serial path and by workers, so there is exactly one
 * definition of what a job means.
 */
export function runJob(
  job: MatchJob,
  population: StrategyPopulation = ACTIVE_POPULATION,
): MatchOutcome {
  const record = runHeadlessMatch({
    players: job.kingdoms.map((kingdomId, i) => ({
      kingdomId,
      ai: factoryFor(population, job.profiles[i]!),
    })),
    seed: job.seed,
    maxTicks: job.maxTicks,
    createAI: factoryFor(population, job.profiles[0]!),
    telemetry: false,
  });

  // Placement: winner first, then reverse elimination order; survivors of a
  // timeout ranked by remaining HP.
  const ordered = [...record.players].sort((x, y) => {
    if (x.id === record.winnerId) return -1;
    if (y.id === record.winnerId) return 1;
    const xd = x.eliminatedAtTick;
    const yd = y.eliminatedAtTick;
    if (xd === null && yd === null) return y.hp - x.hp;
    if (xd === null) return -1;
    if (yd === null) return 1;
    return yd - xd;
  });
  const rank = new Map(ordered.map((p, i) => [p.id, i + 1]));

  let winnerSeat: number | null = null;
  const placements = record.players.map((p, seat) => {
    if (p.id === record.winnerId) winnerSeat = seat;
    return rank.get(p.id)!;
  });

  return {
    id: job.id,
    winnerKingdom: record.winnerKingdom,
    winnerSeat,
    endedAtTick: record.endedAtTick,
    timedOut: record.timedOut,
    placements,
  };
}
